"""Tests for MM-3 figures F1-F8 and interactive companion (#5411).

Acceptance criteria:
- SVG/PNG for F1-F8 generated by script from MM-2 JSON; figure tests check files exist
  and key values match the JSON.
- Interactive F1 (sequence slider) and F2 (gimbal lock vs rotation vector) only;
  no claim that one convention is universally correct.
- Every figure labelled synthetic / model_scenario unless backed by an approved UD release.
- Alt text for each figure.
"""

from __future__ import annotations

from pathlib import Path

from src.tools import motion_measurement_figures as mmf
from src.tools import motion_measurement_fixtures as mm

REPO_ROOT = Path(__file__).resolve().parent.parent
DOCS_DIR = REPO_ROOT / "docs/development/motion-measurement"
FIGURES_DIR = DOCS_DIR / "figures"
COMPANION_PATH = DOCS_DIR / "interactive_companion.html"


def test_figure_metadata_and_alt_text() -> None:
    """Every figure F1-F8 must have accessible alt text and synthetic/model_scenario label."""
    assert len(mmf.FIGURE_NAMES) == 8
    for name in mmf.FIGURE_NAMES:
        meta = mmf.FIGURE_METADATA.get(name)
        assert meta is not None, f"Missing metadata for {name}"
        assert meta["label"] in {"synthetic", "model_scenario"}
        assert len(meta["alt_text"].strip()) > 20, f"Alt text too short for {name}"
        assert len(meta["title"].strip()) > 5, f"Title too short for {name}"


def test_generate_figures_from_json_and_match_values(tmp_path: Path) -> None:
    """Generate figures from MM-2 JSON and verify files exist, are valid, and match JSON."""
    json_path = tmp_path / "fixtures.json"
    json_data = mm.write_results(json_path)
    output_dir = tmp_path / "figures"

    generated = mmf.generate_figures(json_path, output_dir)
    assert len(generated) == 8

    for fig_path in generated:
        assert fig_path.is_file(), f"Generated figure missing: {fig_path}"
        content = fig_path.read_text(encoding="utf-8")
        assert "<svg" in content and "</svg>" in content

        meta = mmf.FIGURE_METADATA[fig_path.name]
        # Label check
        assert meta["label"] in content
        # Alt text in <desc>
        assert meta["alt_text"] in content

    # Key value checks against MM-2 JSON
    f1_text = (output_dir / "f1_cardan_sequences.svg").read_text(encoding="utf-8")
    cardan_diff = f"{json_data['cardan']['max_diff_rad']:.2f}"
    assert cardan_diff in f1_text

    f2_text = (output_dir / "f2_gimbal_lock.svg").read_text(encoding="utf-8")
    assert "90" in f2_text  # pitch 90 deg gimbal lock
    assert "rotvec" in f2_text.lower() or "rotation vector" in f2_text.lower()

    f3_text = (output_dir / "f3_angle_unwrap.svg").read_text(encoding="utf-8")
    wrapped_jump = f"{json_data['unwrap']['wrapped_max_jump_rad']:.2f}"
    assert wrapped_jump in f3_text

    f4_text = (output_dir / "f4_orthogonality_drift.svg").read_text(encoding="utf-8")
    drifted_err = f"{json_data['orthogonality']['drifted_det_error']:.3f}"
    assert drifted_err in f4_text

    f5_text = (output_dir / "f5_quaternion_continuity.svg").read_text(encoding="utf-8")
    min_norm = f"{json_data['quaternion']['min_norm_without_continuity']:.2f}"
    assert min_norm in f5_text

    f6_text = (output_dir / "f6_helical_axis_error.svg").read_text(encoding="utf-8")
    step_val = str(json_data["helical_axis"]["steps_rad"][0])
    assert step_val in f6_text

    f7_text = (output_dir / "f7_angular_velocity_differences.svg").read_text(encoding="utf-8")
    euler_err = f"{json_data['angular_velocity']['pitch_30_deg']['euler_difference_max_error']:.2f}"
    assert euler_err in f7_text

    f8_text = (output_dir / "f8_xfactor_variants.svg").read_text(encoding="utf-8")
    spread_val = f"{json_data['xfactor']['spread_deg']:.1f}"
    assert spread_val in f8_text


def test_interactive_companion_requirements() -> None:
    """Interactive companion covers F1 and F2, is neutral, and labelled synthetic."""
    assert COMPANION_PATH.is_file(), f"Interactive companion missing at {COMPANION_PATH}"
    html = COMPANION_PATH.read_text(encoding="utf-8")

    # Interactive F1 (sequence slider / selector) and F2 (gimbal lock vs rotation vector)
    assert "F1" in html and "sequence" in html.lower()
    assert "F2" in html and ("gimbal lock" in html.lower() or "gimbal" in html.lower())
    assert "rotvec" in html.lower() or "rotation vector" in html.lower()

    # Neutrality: no claim that one convention is universally correct
    assert (
        "no convention is universally correct" in html.lower()
        or "no representation is universally correct" in html.lower()
        or "convention card" in html.lower()
    )

    # Every figure labelled synthetic / model_scenario
    assert "synthetic" in html.lower() or "model_scenario" in html.lower()


def test_committed_figures_exist_and_match_canonical_fixtures() -> None:
    """Verify that committed figures exist in docs/development/motion-measurement/figures."""
    assert FIGURES_DIR.is_dir(), f"Figures directory missing: {FIGURES_DIR}"
    for name in mmf.FIGURE_NAMES:
        fig_path = FIGURES_DIR / name
        assert fig_path.is_file(), f"Committed figure missing: {fig_path}"
        assert fig_path.stat().st_size > 0
        content = fig_path.read_text(encoding="utf-8")
        assert "<svg" in content and "</svg>" in content
