"""Generate the spatial arm viewer's frames from the cited 3D arm chain (#4973).

Phase 2 of the swing viewer (ADR 0002): the frames are precomputed from
``JOHNSON_2015_ARM`` in ``src/affine_control/golf_model_3d.py``, so the browser
runs no physics. The motion is a prescribed sweep inside the joint limits, not a
swing; the caveats the page must show travel inside the payload.
"""

from __future__ import annotations

import argparse
import json
import logging
from pathlib import Path

from src.affine_control.arm_viewer_frames import CAVEATS, build_frames, build_joint_table
from src.affine_control.golf_model_3d import JOHNSON_2015_ARM

logger = logging.getLogger(__name__)

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "js" / "arm-viewer-data.js"


def build_payload() -> dict[str, object]:
    """Model metadata, caveats, joint table and frames for the viewer."""
    return {
        "label": (
            "Spatial (3D) rigid arm chain after Johnson (2015). Prescribed joint sweep, "
            "not a measured or simulated swing; no shaft, no torso."
        ),
        "source": "src/affine_control/golf_model_3d.py",
        "generator": "scripts/generate_arm_viewer_data.py",
        "issue": 4973,
        "provenance": JOHNSON_2015_ARM.provenance,
        "caveats": list(CAVEATS),
        "joints": build_joint_table(),
        "frames": build_frames(),
    }


def render(payload: dict[str, object]) -> str:
    """JavaScript module exposing the payload to the page and to Jest."""
    body = json.dumps(payload, separators=(",", ":"), sort_keys=True)
    return (
        "// Generated by scripts/generate_arm_viewer_data.py (#4973). Do not edit.\n"
        f"(function (root) {{\n  var data = {body};\n"
        "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n"
        "  else root.AffineDriftArmViewerData = data;\n"
        "})(typeof self !== 'undefined' ? self : this);\n"
    )


def stale() -> bool:
    """Whether the committed data module differs from a fresh build."""
    return not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != render(build_payload())


def main(argv: list[str] | None = None) -> int:
    """Write the data module, or with ``--check`` fail when it is stale."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    if args.check:
        if stale():
            logger.error("%s is stale; run python -m scripts.generate_arm_viewer_data", OUTPUT)
            return 1
        return 0
    OUTPUT.write_text(render(build_payload()), encoding="utf-8", newline="\n")
    logger.info("wrote %s", OUTPUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
