"""Write the 3D golfer viewer's synthetic clip as a JS data module, so it works offline (#5425).

``--check`` fails when the committed module is stale.
"""

from __future__ import annotations

import argparse
import json
import logging
from pathlib import Path

from src.affine_control.motion_clip_frames import CAVEATS, MARKERS, SEGMENTS, build_frames

logger = logging.getLogger(__name__)

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "js" / "motion-clip-data.js"


def build_payload() -> dict[str, object]:
    """Label, caveats, skeleton and frames for the viewer."""
    return {
        "label": (
            "A synthetic stick-figure golf swing, hand-shaped from keyframed angles: "
            "not licensed motion capture and not a traced UpstreamDrift render."
        ),
        "source": "src/affine_control/motion_clip_frames.py",
        "generator": "scripts/generate_motion_clip_data.py",
        "issue": 5425,
        "caveats": list(CAVEATS),
        "markers": list(MARKERS),
        "segments": [list(pair) for pair in SEGMENTS],
        "frames": build_frames(),
    }


def render(payload: dict[str, object]) -> str:
    """JavaScript module exposing the payload to the page and to Jest."""
    body = json.dumps(payload, separators=(",", ":"), sort_keys=True)
    return (
        "// Generated by scripts/generate_motion_clip_data.py (#5425). Do not edit.\n"
        f"(function (root) {{\n  var data = {body};\n"
        "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n"
        "  else root.AffineDriftMotionClipData = data;\n"
        "})(typeof self !== 'undefined' ? self : this);\n"
    )


def stale() -> bool:
    """Whether the committed data module differs from a fresh build."""
    return not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != render(build_payload())


def main(argv: list[str] | None = None) -> int:
    """Write the data module, or with ``--check`` fail when it is stale."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    if args.check:
        if stale():
            logger.error("%s is stale; run python -m scripts.generate_motion_clip_data", OUTPUT)
            return 1
        return 0
    OUTPUT.write_text(render(build_payload()), encoding="utf-8", newline="\n")
    logger.info("wrote %s", OUTPUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
