"""Generate the on-disk golfer joint table from verified UpstreamDrift git objects."""

from __future__ import annotations

import argparse
import hashlib
import math
import subprocess
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import Protocol

from defusedxml import ElementTree as ET

PIN = "8cf45c0a986bca8c5fe414ab2858925a4dcd9a26"
SOURCE_SHA256 = "1a91720cd7539fb009b2ab42b62526213152d78cf7af5bb1865913c2d6e9f824"
SOURCES = tuple(
    f"src/engines/physics_engines/{engine}/models/generated/golfer.urdf"
    for engine in ("pinocchio", "drake")
)
OUTPUT = Path(__file__).resolve().parents[1] / "models/_generated/golf-urdf-joints.qmd"


class _Attributes(Protocol):
    @property
    def attrib(self) -> Mapping[str, str]: ...


class _Element(Protocol):
    def find(self, path: str) -> _Attributes | None: ...


@dataclass(frozen=True)
class Joint:
    """One source joint; ordinal is deliberately independent of engine indices."""

    name: str
    kind: str
    parent: str
    child: str
    axis: str
    limits: str


def verify_source(data: bytes, expected: str) -> None:
    """Reject bytes differing from the pinned source digest before parsing."""
    if hashlib.sha256(data).hexdigest() != expected:
        raise ValueError("Upstream URDF SHA-256 mismatch")


def _attribute(joint: _Element, tag: str, attribute: str) -> str:
    element = joint.find(tag)
    if element is None or attribute not in element.attrib:
        raise ValueError(f"Missing {tag}/{attribute}")
    return str(element.attrib[attribute])


def _axis_and_limits(joint: _Element) -> tuple[str, str]:
    axis = _attribute(joint, "axis", "xyz")
    values = [float(value) for value in axis.split()]
    lower = _attribute(joint, "limit", "lower")
    upper = _attribute(joint, "limit", "upper")
    bounds = [float(lower), float(upper)]
    if (
        len(values) != 3
        or not all(math.isfinite(v) for v in values + bounds)
        or not math.isclose(sum(v * v for v in values), 1.0)
        or bounds[0] > bounds[1]
    ):
        raise ValueError("Invalid axis or limits")
    return axis, f"[{lower}, {upper}]"


def parse_joints(data: bytes) -> list[Joint]:
    """Extract explicit fixed/revolute joints; reject missing or unsupported data.

    Postcondition: names are unique and each revolute axis is a finite unit vector
    with finite, ordered limits. No anatomical signs or native indices are inferred.
    """
    root = ET.fromstring(data)
    if root.tag != "robot":
        raise ValueError("Expected URDF robot")
    rows: list[Joint] = []
    names: set[str] = set()
    for joint in root.findall("joint"):
        name, kind = joint.get("name", ""), joint.get("type", "")
        if not name or name in names or kind not in {"fixed", "revolute"}:
            raise ValueError("Unsupported joint or duplicate/missing name")
        names.add(name)
        axis, limits = _axis_and_limits(joint) if kind == "revolute" else ("—", "—")
        rows.append(
            Joint(
                name,
                kind,
                _attribute(joint, "parent", "link"),
                _attribute(joint, "child", "link"),
                axis,
                limits,
            )
        )
    if not rows:
        raise ValueError("URDF has no joints")
    return rows


def render_table(rows: list[Joint]) -> str:
    """Render source-order rows without representing ordinals as q/v indices."""
    lines = [
        "<!-- Generated by scripts/generate_urdf_golf_map.py; do not edit. -->",
        "",
        "| XML Row | Joint | Type | Parent → Child | Local Axis | Range (rad) |",
        "|---|---|---|---|---|---|",
    ]
    for ordinal, row in enumerate(rows):
        axis = f"`{row.axis}`" if row.kind == "revolute" else row.axis
        lines.append(
            f"| {ordinal} | `{row.name}` | {row.kind} | "
            f"`{row.parent}` → `{row.child}` | {axis} | {row.limits} |"
        )
    return "\n".join(lines) + "\n"


def main() -> int:
    """Read both pinned git objects, require byte identity, and generate or check."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--upstream", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    sources = [
        subprocess.run(
            ["git", "-C", str(args.upstream), "show", f"{PIN}:{path}"],
            check=True,
            capture_output=True,
            timeout=30,
        ).stdout
        for path in SOURCES
    ]
    for source in sources:
        verify_source(source, SOURCE_SHA256)
    if sources[0] != sources[1]:
        raise ValueError("Drake and Pinocchio golfer URDFs differ")
    table = render_table(parse_joints(sources[0]))
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != table:
            raise ValueError("Generated URDF joint table is stale")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(table, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
