"""Render pinned Simscape golfer-scapula/2.0 DOF and sign tables from JSON specs."""

from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import Any

logger = logging.getLogger(__name__)

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_SIMSCAPE_SPEC = ROOT / "data/upstreamdrift_golf_models/simscape_golfer_scapula_v2.json"
DEFAULT_SIMSCAPE_QMD_OUT = ROOT / "models/_generated/golf-model-maps-simscape.qmd"


def load_simscape_spec(path: Path = DEFAULT_SIMSCAPE_SPEC) -> dict[str, Any]:
    """Load and validate structural counts of the Simscape golfer-scapula/2.0 spec."""
    raw = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(raw, dict):
        msg = "simscape spec root must be a JSON object"
        raise ValueError(msg)
    dofs = raw.get("dofs")
    if not isinstance(dofs, list):
        msg = "simscape spec missing 'dofs' array"
        raise ValueError(msg)

    expected_total = int(raw.get("total_dofs", -1))
    if len(dofs) != expected_total:
        msg = f"expected {expected_total} total DOFs, found {len(dofs)}"
        raise ValueError(msg)

    mapped = [d for d in dofs if d.get("simscape_var", "—") != "—"]
    validated = [d for d in mapped if bool(d.get("validated"))]
    if len(mapped) != int(raw.get("mapped_simscape_dofs", -1)):
        msg = f"mapped_simscape_dofs mismatch: expected {raw.get('mapped_simscape_dofs')}, got {len(mapped)}"
        raise ValueError(msg)
    if len(validated) != int(raw.get("validated_simscape_dofs", -1)):
        msg = f"validated_simscape_dofs mismatch: expected {raw.get('validated_simscape_dofs')}, got {len(validated)}"
        raise ValueError(msg)

    logger.debug("Loaded Simscape spec %s (%d DOFs)", raw.get("model_id"), len(dofs))
    return raw


def _fmt_sign(sign: float | None) -> str:
    if sign is None:
        return "—"
    if sign > 0:
        return "+1"
    if sign < 0:
        return "-1"
    return "0"


def render_simscape_qmd(spec: dict[str, Any]) -> str:
    """Render deterministic Quarto markdown tables for ``golfer-scapula/2.0``."""
    commit = str(spec["upstream_commit"])
    ident = spec["identification"]
    dofs: list[dict[str, Any]] = spec["dofs"]

    lines = [
        "<!-- Generated by scripts/generate_golf_model_maps.py (--simscape); do not edit. -->",
        "",
        f"Pinned UpstreamDrift commit "
        f"[`{commit}`](https://github.com/D-sorganization/UpstreamDrift/tree/{commit}) "
        f"(`src/motion_capture/reconstruct/model/golfer.py`, "
        f"`src/motion_capture/reconstruct/model/simscape.py`).",
        "",
        "| Total DOFs (`q`) | Mapped Simscape variables | Sensor-validated DOFs | Max residual |",
        "|---:|---:|---:|---:|",
        f"| {spec['total_dofs']} | {spec['mapped_simscape_dofs']} | "
        f"{spec['validated_simscape_dofs']} | {ident['fit_residual_rad_max']:g} rad |",
        "",
        "| `q` idx | DOF | Parent | Axes | Simscape variable | Sign | Range | Validated | Log column |",
        "|---:|---|---|---|---|---:|---|---|---|",
    ]

    for row in dofs:
        sim_var = row["simscape_var"]
        sim_cell = f"`{sim_var}`" if sim_var != "—" else "—"
        log_col = row["log_column"]
        log_cell = f"`{log_col}`" if log_col != "—" else "—"
        valid_cell = "yes" if row["validated"] else "no"
        lines.append(
            "| "
            + " | ".join(
                [
                    str(row["index"]),
                    f"`{row['dof']}`",
                    f"`{row['parent']}`",
                    f"`{row['axes']}`",
                    sim_cell,
                    _fmt_sign(row["sign"]),
                    row["range_display"],
                    valid_cell,
                    log_cell,
                ]
            )
            + " |"
        )

    lines.extend(
        [
            "",
            "Fixed head/ankle frames (`hub`→`nose` head 0.18 m; `left_ankle`, `right_ankle` zero-axis frames) contribute 0 DOFs. "
            "Exported Simscape CSV angles multiply the internal radian coordinate by `sign` and convert to degrees; legs, head, and wrist DOFs are unvalidated against MATLAB logs.",
            "",
        ]
    )
    return "\n".join(lines)
