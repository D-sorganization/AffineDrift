"""Deterministic accessible rendering for the falsification atlas."""

from __future__ import annotations

from html import escape
from pathlib import PurePosixPath

from .models import AtlasDocument, AtlasRecord


def _row(term: str, description: str) -> str:
    """Render one semantic definition-list row."""
    return f"<dt>{escape(term)}</dt><dd>{escape(description)}</dd>"


def _critique_href(record: AtlasRecord) -> str:
    """Return the public route for one canonical critique source."""
    path = PurePosixPath(record.critique_source_path).with_suffix(".html")
    return f"../{path.as_posix()}"


def _evidence_list(record: AtlasRecord) -> str:
    """Render exact evidence artifact identifiers without inventing links."""
    items = "".join(f"<li><code>{escape(item)}</code></li>" for item in record.evidence_artifacts)
    return (
        "<details><summary>Evidence artifacts</summary>"
        f'<ul class="atlas-evidence">{items}</ul></details>'
    )


def _render_record(record: AtlasRecord, document: AtlasDocument) -> str:
    """Render one complete record with color-independent semantic labels."""
    monograph = "proximal_distal_energy_transfer/index.html#" + escape(
        record.chapter_anchor, quote=True
    )
    source = (
        f"https://github.com/{document.source_repository}/tree/"
        f"{document.source_commit}/{document.source_root}"
    )
    readiness = "../models/research-protocol-readiness.html#" + escape(
        record.readiness_protocol_id, quote=True
    )
    rows = [
        _row("Source Claim", f"{record.claim_id}: {record.claim}"),
        _row("Source-Reported Claim Status", record.evidence_state),
        _row("Source-Declared Model Domain", record.model_domain),
        _row("Source Uncertainty Boundary", record.uncertainty),
        _row("Editorial Alternative", record.alternative_mechanism),
        _row("Editorial Discriminating Comparison", record.discriminating_measurement),
        _row("Source-Reported Falsifier", record.falsifier),
        _row("Editorial Review Question", record.critique_question),
        _row("Critique Ledger Disposition", f"{record.critique_id}: {record.critique_state}"),
        _row(
            "Readiness Record",
            f"{record.readiness_protocol_id}: {record.readiness_state} "
            f"({record.readiness_evidence_origin})",
        ),
        _row(
            "Registered Validation Release",
            f"{record.validation_release_state}: {record.validation_release_next_gate}",
        ),
        _row("Registered Workflow", f"{record.workflow_state}: {record.workflow_reason}"),
    ]
    links = (
        f'<p><a href="{monograph}">Read the exact monograph section</a> · '
        f'<a href="{escape(_critique_href(record), quote=True)}">Open the governed critique</a> · '
        f'<a href="{readiness}">Inspect exact readiness record</a> · '
        f'<a href="{escape(source, quote=True)}">Inspect exact source revision</a></p>'
    )
    return (
        f'<section class="falsification-atlas-record" id="{escape(record.atlas_id, quote=True)}">'
        f"<h2>{escape(record.title)}</h2><dl>{''.join(rows)}</dl>{links}"
        f"{_evidence_list(record)}</section>"
    )


def render_atlas(document: AtlasDocument) -> str:
    """Render the complete static atlas projection deterministically."""
    header = (
        "<!-- DO NOT EDIT. Generated by "
        "scripts/generate_proximal_distal_falsification_atlas.py. -->\n"
        '<div class="atlas-authority" role="note" aria-label="Atlas authority">'
        f"<p><strong>Atlas Workflow Registration:</strong> {escape(document.provider_state)}. "
        f"{escape(document.provider_reason)} "
        f'<a href="{escape(document.provider_tracking_issue, quote=True)}">'
        "Track provider publication</a>.</p>"
        "<p><strong>Imported Monograph Revision:</strong> "
        f"<code>{escape(document.source_commit)}</code>.</p>"
        "</div>\n"
    )
    records = "\n".join(_render_record(record, document) for record in document.records)
    return f"{header}{records}\n"
